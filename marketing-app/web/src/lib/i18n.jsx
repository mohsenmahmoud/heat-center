const I18n = createContext(null);

const stored = (key, fallback) => {
  try {
    return localStorage.getItem(key) || fallback;
  } catch {
    return fallback;
  }
};
const store = (key, value) => {
  try {
    localStorage.setItem(key, value);
  } catch {
    /* private mode: preference just isn't remembered */
  }
};

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => stored('qms-lang', 'ar'));
  const [theme, setTheme] = useState(() => stored('qms-theme', 'dark'));

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    store('qms-lang', lang);
  }, [lang]);
  useEffect(() => {
    document.documentElement.classList.toggle('dark', theme === 'dark');
    store('qms-theme', theme);
  }, [theme]);

  const value = useMemo(
    () => ({
      lang,
      theme,
      t: (key) => key.split('.').reduce((o, k) => o?.[k], dict[lang]) ?? key,
      toggleLang: () => setLang((l) => (l === 'ar' ? 'en' : 'ar')),
      toggleTheme: () => setTheme((t) => (t === 'dark' ? 'light' : 'dark')),
      // Pick the right side of a bilingual {ar, en} server message.
      pick: (msg) => (typeof msg === 'string' ? msg : msg?.[lang] || msg?.en || ''),
    }),
    [lang, theme],
  );
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

export const useI18n = () => useContext(I18n);
